#!/usr/bin/env python3
"""Measure every control in the prototype and write docs/design/ui-layout.json (design px, 2500x1000).
Needs Microsoft Edge (headless). Run from the repo root, then run tools/gen_ui_layout.py."""
import html, json, re, subprocess, sys, tempfile, os

EDGE = os.environ.get('EDGE', '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge')
PROTO = 'docs/design/prototype/index.html'
OUT = 'docs/design/ui-layout.json'

JS = r'''
<script>
window.addEventListener('load',function(){setTimeout(function(){try{
var P=document.getElementById('panel'),pr=P.getBoundingClientRect(),k=pr.width/2500;
function R(e){var r=e.getBoundingClientRect();return [Math.round((r.left-pr.left)/k),Math.round((r.top-pr.top)/k),Math.round(r.width/k),Math.round(r.height/k)];}
function vis(e){var r=e.getBoundingClientRect();return r.width>0&&r.height>0&&e.offsetParent!==null;}
function all(sel,f){var a=[];document.querySelectorAll('#panel '+sel).forEach(function(e){if(vis(e)&&!e.closest('#settings')&&!e.closest('#drop'))a.push(f(e));});return a;}
function snap(){return {
keys:all('.key',function(e){return {label:e.textContent.trim().replace(/\s+/g,' '),shape:/rect/.test(e.className)?'rect':'square',era5only:/e5/.test(e.className),rect:R(e),section:(e.closest('.frame')||{id:'top'}).id||'top',parent:e.parentElement.id||'',drawer:!!e.closest('#intp')};}),
knobs:all('.knob',function(e){var l=e.querySelector('.kl'),v=e.querySelector('.vb');return {id:e.dataset.k,label:l?l.textContent.trim():'',labelRect:l?R(l):null,dial:R(e.querySelector('.dial')),value:v?R(v):null,era5only:/e5/.test(e.className),drawer:!!e.closest('#intp')};}),
dgroups:all('#intp .dgt',function(e){return {title:e.textContent.trim(),rect:R(e)};}),
frames:all('.frame',function(e){var h=e.querySelector('h2');return {id:e.id,title:h?h.textContent:'',rect:R(e),titleRect:h?R(h):null};}),
meterGroups:all('.mgrp',function(e){return {rect:R(e),parent:e.parentElement.id,hit:R(e.querySelector('.cliphit')),cols:R(e.querySelector('.cols'))};}),
panes:all('.pane.ms',function(e){return {text:e.textContent.trim(),rect:R(e)};}),
misc:[['lcd','#lcd'],['dpanel','#dpanel'],['eqgraph','#eqgraph'],['version','#ver'],['rule','.rule'],['logo','#top .lab'],['l1','#l1'],['l2','#l2'],['intp','#intp'],['intptitle','#intp > h2']].map(function(a){var e=document.querySelector('#panel '+a[1]);return {name:a[0],rect:e&&vis(e)?R(e):null};})};}
var out={};
out.era7_fx_delay=snap();
function key(t){var f=[].filter.call(document.querySelectorAll('#fxhead .key'),function(e){return vis(e)&&e.textContent.trim().toLowerCase()==t;})[0];if(f)f.click();}
['echo','mod','off'].forEach(function(t){key(t);out['era7_fx_'+t]=snap();});
key('delay');
var e5=document.querySelector('#erakeys .key[data-era="5"]');if(e5){e5.click();out.era5_fx_delay=snap();var ik=[].filter.call(document.querySelectorAll('#panel .key'),function(e){return vis(e)&&/^Int/.test(e.textContent.trim());})[0];if(ik){ik.click();out.era5_intparam=snap();ik.click();}key('pitch');out.era5_fx_pitch=snap();key('pan');out.era5_fx_pan=snap();key('delay');var dg=[].filter.call(document.querySelectorAll('#panel .key'),function(e){return e.textContent.trim()=='Digital';})[0];if(dg){dg.click();out.era5_eq_digital=snap();}}
var pre=document.createElement('pre');pre.id='OUT';pre.textContent=JSON.stringify(out);document.body.appendChild(pre);
}catch(e){var p=document.createElement('pre');p.id='ERR';p.textContent=e.stack;document.body.appendChild(p);}},1500);});
</script>'''

src = open(PROTO).read().replace('../../../assets', os.path.abspath('assets'))
with tempfile.NamedTemporaryFile('w', suffix='.html', delete=False) as f:
    f.write(src + JS)
dom = subprocess.run([EDGE, '--headless=new', '--window-size=2532,1080', '--force-device-scale-factor=1',
                      '--virtual-time-budget=10000', '--allow-file-access-from-files', '--dump-dom', 'file://' + f.name],
                     capture_output=True, text=True).stdout
os.unlink(f.name)
m = re.search(r'<pre id="OUT">(.*?)</pre>', dom, re.S)
if not m:
    e = re.search(r'<pre id="ERR">(.*?)</pre>', dom, re.S)
    sys.exit('export failed: ' + (html.unescape(e.group(1)) if e else 'no output'))
json.dump({'_note': 'Generated by tools/export_ui_layout.py from docs/design/prototype/index.html (2500x1000 design px; rect=[x,y,w,h]).',
           'canvas': [2500, 1000], 'states': json.loads(html.unescape(m.group(1)))}, open(OUT, 'w'), separators=(',', ':'))
print('wrote', OUT)
