#!/usr/bin/env python3
"""Generate src/plugin/ui/UiLayout.h from docs/design/ui-layout.json and the knob specs in the prototype.
Run from the repo root: python3 tools/gen_ui_layout.py"""
import json, re

LAYOUT = 'docs/design/ui-layout.json'
PROTO = 'docs/design/prototype/index.html'
OUT = 'src/plugin/ui/UiLayout.h'
FX = ['delay', 'echo', 'mod', 'pitch', 'pan', 'off']  # bit order for fxMask (1, 2, 4, 8, 16, 32)
FX_STATES = {'delay': ['era7_fx_delay', 'era5_fx_delay'], 'echo': ['era7_fx_echo'], 'mod': ['era7_fx_mod'],
             'pitch': ['era5_fx_pitch'], 'pan': ['era5_fx_pan'], 'off': ['era7_fx_off']}

states = json.load(open(LAYOUT))['states']
src = open(PROTO).read()

specs = {}
for m in re.finditer(r"\{ id: '(\w+)', label: '([^']*)', min: (-?[\d.]+), max: (-?[\d.]+), def: (-?[\d.]+), fmt: '(\w+)'([^}]*)\}", src):
    i, lab, lo, hi, df, fmt, rest = m.groups()
    specs[i] = dict(lo=float(lo), hi=float(hi), df=float(df), fmt=fmt, log='log: true' in rest,
                    step=float(re.search(r'step: ([\d.]+)', rest).group(1)) if 'step:' in rest else 0.0)

# Digital EQ knob specs are built in a loop in the prototype, so they are listed here (ranges from EQSETS).
for b, (flo, fhi, fdef) in {'lo': (32, 2200, 120), 'mid': (250, 5600, 1000), 'hi': (500, 16000, 8000)}.items():
    specs['d_%sf' % b] = dict(lo=flo, hi=fhi, df=fdef, fmt='hz', log=True, step=0.0)
    specs['d_%sg' % b] = dict(lo=-15.0, hi=15.0, df=0.0, fmt='db', log=False, step=0.0)
    specs['d_%sq' % b] = dict(lo=0.1, hi=5.0, df=1.0, fmt='q', log=False, step=0.0)
for b, (flo, fhi, fdef) in {'lo': (50, 700, 200), 'mid': (350, 5000, 1000), 'hi': (2000, 20000, 8000)}.items():
    specs['a_%sf' % b] = dict(lo=flo, hi=fhi, df=fdef, fmt='hz', log=True, step=0.0)
    specs['a_%sg' % b] = dict(lo=-15.0, hi=15.0, df=0.0, fmt='db', log=False, step=0.0)

def mask(entries_by_state, keyf):
    seen = {}
    for si, fx in enumerate(FX):
        for name in FX_STATES[fx]:
            for e in states[name][entries_by_state]:
                seen.setdefault(keyf(e), [e, 0])[1] |= 1 << si
    full = (1 << len(FX)) - 1
    return [(e, 0 if m == full else m) for e, m in seen.values()]

def q(s): return json.dumps(s, ensure_ascii=True)

keys = [(k, m, 1 if k['rect'][0] > 1900 and k['label'] in ('Peak', 'Shelf') and False else 0) for k, m in mask('keys', lambda k: (k['label'], tuple(k['rect'])))]
knobs = mask('knobs', lambda k: k['id'])

# Digital EQ view (era 5): extra knobs and the two Peak/Shelf keys, from their own snapshot.
dig = states['era5_eq_digital']
dig_knobs = [(k, 0) for k in dig['knobs'] if k['id'].startswith('d_')]
dig_keys = [(k, 0, 2) for k in dig['keys'] if k['label'] in ('Peak', 'Shelf') and k['rect'][0] > 1900]
keys = [(k, m, v) for k, m, v in keys] + dig_keys
def knob_view(i): return 3 if i in drawer_ids else 1 if i.startswith('a_') else 2 if i.startswith('d_') else 0
knobs = knobs + dig_knobs

# INT PARAM drawer (view 3): its knobs and keys, from the snapshot with the drawer open.
drw = states['era5_intparam']
knobs = knobs + [(k, 0) for k in drw['knobs'] if k.get('drawer')]
keys = keys + [(k, 0, 3) for k in drw['keys'] if k.get('drawer')]
drawer_ids = {k['id'] for k in drw['knobs'] if k.get('drawer')}
drw_misc = {m['name']: m['rect'] for m in drw['misc']}
frames = states['era5_fx_delay']['frames']
mg = states['era5_fx_delay']['meterGroups']
panes = states['era5_fx_delay']['panes']
misc = {m['name']: m['rect'] for m in states['era5_fx_delay']['misc']}
misc['eqgraph_digital'] = [m for m in dig['misc'] if m['name'] == 'eqgraph'][0]['rect']

L = ['// GENERATED by tools/gen_ui_layout.py from docs/design/ui-layout.json. Do not edit by hand.',
     '// Design units: pixels in the 2500 x 1000 panel. fxMask bits: delay=1, echo=2, mod=4, pitch=8, pan=16, off=32',
     '// (0 = always shown). view: 0 always, 1 analogue EQ, 2 digital EQ, 3 INT PARAM drawer.',
     '#pragma once', '', 'namespace yrev::ui', '{',
     '    struct Rect { int x, y, w, h; };',
     '    struct KeyDef { const char* label; bool rect; const char* group; bool era5; int fxMask; int view; Rect r; };',
     '    struct KnobDef { const char* id; const char* label; Rect labelR; Rect dial; Rect value; bool era5; int fxMask; int view;',
     '                     double lo, hi, def; const char* fmt; bool log; double step; };',
     '    struct FrameDef { const char* title; Rect r; Rect titleR; };', '',
     '    inline constexpr int kDesignW = 2500, kDesignH = 1000;', '']
L.append('    inline constexpr KeyDef kKeys[] = {')
for k, m, v in keys:
    L.append('        { %s, %s, %s, %s, %d, %d, { %d, %d, %d, %d } },' % (q(k['label']), 'true' if k['shape']=='rect' else 'false', q(k['parent']), 'true' if k['era5only'] else 'false', m, v, *k['rect']))
L.append('    };\n')
L.append('    inline constexpr KnobDef kKnobs[] = {')
for k, m in knobs:
    s = specs.get(k['id'])
    if not s:
        s = dict(lo=0, hi=1, df=0, fmt='x', log=False, step=0)
    lr = k['labelRect'] or [0, 0, 0, 0]
    L.append('        { %s, %s, { %d, %d, %d, %d }, { %d, %d, %d, %d }, { %d, %d, %d, %d }, %s, %d, %d, %r, %r, %r, %s, %s, %r },' % (
        q(k['id']), q(k['label']), *lr, *k['dial'], *k['value'], 'true' if k['era5only'] else 'false', m, knob_view(k['id']),
        s['lo'], s['hi'], s['df'], q(s['fmt']), 'true' if s['log'] else 'false', s['step']))
L.append('    };\n')
L.append('    inline constexpr FrameDef kFrames[] = {')
for f in frames:
    tr = f['titleRect'] or [0, 0, 0, 0]
    L.append('        { %s, { %d, %d, %d, %d }, { %d, %d, %d, %d } },' % (q(f['title']), *f['rect'], *tr))
L.append('    };\n')
L.append('    inline constexpr FrameDef kDrawer = { %s, { %d, %d, %d, %d }, { %d, %d, %d, %d } };' % (q('Internal parameters'), *drw_misc['intp'], *drw_misc['intptitle']))
L.append('    struct GroupDef { const char* title; Rect r; };')
L.append('    inline constexpr GroupDef kDrawerGroups[] = {')
for g in drw['dgroups']:
    L.append('        { %s, { %d, %d, %d, %d } },' % (q(g['title']), *g['rect']))
L.append('    };\n')
def R(r): return '{ %d, %d, %d, %d }' % tuple(r)
for g in mg:
    nm = 'kMeterOut' if g['parent'] == 'metersec' else 'kMeterIn'
    L.append('    inline constexpr Rect %sCols = %s, %sClipHit = %s;' % (nm, R(g['cols']), nm, R(g['hit'])))
L.append('    inline constexpr Rect kPaneMono = %s, kPaneStereo = %s, kPaneTrue = %s;' % tuple(R(p['rect']) for p in panes))
for n, v in [('Lcd', 'lcd'), ('DisplayPanel', 'dpanel'), ('EqGraph', 'eqgraph'), ('EqGraphDigital', 'eqgraph_digital'), ('Version', 'version'), ('Rule', 'rule'), ('Logo', 'logo'), ('L1', 'l1'), ('L2', 'l2')]:
    L.append('    inline constexpr Rect k%s = %s;' % (n, R(misc[v])))
L.append('}')
open(OUT, 'w').write('\n'.join(L) + '\n')

# Tooltips: one source (docs/design/ui-tooltips.json) feeds the plugin header and the prototype.
tips = json.load(open('docs/design/ui-tooltips.json'))
T = ['// GENERATED by tools/gen_ui_layout.py from docs/design/ui-tooltips.json. Do not edit by hand.', '#pragma once', '',
     'namespace yrev::ui', '{', '    struct Tip { const char* key; const char* text; };']
for group in ('knobs', 'keys', 'areas', 'overlay'):
    T.append('    inline constexpr Tip kTips_%s[] = {' % group)
    for k, v in tips[group].items():
        T.append('        { %s, %s },' % (q(k), q(v)))
    T.append('    };')
T.append('}')
open('src/plugin/ui/UiTooltips.h', 'w').write('\n'.join(T) + '\n')
proto = open(PROTO).read()
proto = re.sub(r'/\*TIPS\*/.*?/\*END\*/', lambda m: '/*TIPS*/var TIPS = ' + json.dumps(tips, ensure_ascii=False) + ';/*END*/', proto, flags=re.S)
open(PROTO, 'w').write(proto)
print('keys', len(keys), 'knobs', len(knobs), 'missing specs', [k['id'] for k, _ in knobs if k['id'] not in specs])
